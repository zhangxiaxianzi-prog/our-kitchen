// 同一道菜在图片里出现两次时只留一份，荤素按食材算，含肉的豆腐不会算素菜。
export function initialMenu(): Dish[] {
  const seen = new Set<string>();
  return columns.flatMap(c => c.split('\n')).flatMap((line, i) => {
    const [name, list] = line.split('|');
    const signature = name.replace(/^鸡蛋炒木耳$/, '木耳炒蛋').replace(/^鸡蛋炒西葫芦$/, '西葫芦炒蛋');
    if (seen.has(signature)) return [];
    seen.add(signature);
    const ingredients = list.split(',');
    return [{ id: `menu-${i}`, name, ingredients, kind: ingredients.some(x => meat.has(x)) ? 'meat' : 'veg', active: true, source: '截图菜名 · 食材按常见做法整理，可修改' }];
  });
}
// 只合并确定是同一种食材的名字，不把所有绿叶菜都当成青菜。
export function ingredientName(value: string): string {
  const n = value.trim();
  const aliases: Record<string, string> = { 西红柿: '番茄', 马铃薯: '土豆', 洋芋: '土豆', 大白菜: '白菜', 卷心菜: '包菜', 圆白菜: '包菜', 豆腐干: '豆干', 千张结: '千张', 莲藕段: '莲藕' };
  return aliases[n] || n;
}
